func TestResolveCIProvider_AutoAndExplicit(t *testing.T) {
	cfg := &Config{}

	// 1. Default auto on Pigweed host -> BuildbucketProvider
	p1 := ResolveCIProvider(cfg, DefaultProjectConfig(), nil, "pigweed-review.googlesource.com", nil)
	if p1.Name() != "buildbucket" {
		t.Errorf("expected buildbucket provider for pigweed host, got %q", p1.Name())
	}

	// 2. Default auto on Android Gerrit host -> CompositeCIProvider
	p2 := ResolveCIProvider(cfg, DefaultProjectConfig(), nil, "android-review.googlesource.com", nil)
	if p2.Name() != "composite" {
		t.Errorf("expected composite provider for android-review host, got %q", p2.Name())
	}

	// 3. Default auto on non-Android host when change has Presubmit-Ready label -> CompositeCIProvider
	changeWithLabel := &gerrit.ChangeInfo{
		Labels: map[string]gerrit.LabelInfo{
			"Presubmit-Ready": {},
		},
	}
	p3 := ResolveCIProvider(cfg, DefaultProjectConfig(), nil, "acme-review.googlesource.com", changeWithLabel)
	if p3.Name() != "composite" {
		t.Errorf("expected composite provider when change has Presubmit-Ready label, got %q", p3.Name())
	}

	// 4. Default auto on non-Android host when change has TreeHugger message -> CompositeCIProvider
	changeWithTH := &gerrit.ChangeInfo{
		Messages: []gerrit.ChangeMessageInfo{
			{Tag: "autogenerated:TreeHugger:Verify-Start"},
		},
	}
	p4 := ResolveCIProvider(cfg, DefaultProjectConfig(), nil, "acme-review.googlesource.com", changeWithTH)
	if p4.Name() != "composite" {
		t.Errorf("expected composite provider when change has TreeHugger message, got %q", p4.Name())
	}

	// 5. Explicit busytown only
	pcfgBusytown := DefaultProjectConfig()
	pcfgBusytown.CI.Providers = []string{"busytown"}
	p5 := ResolveCIProvider(cfg, pcfgBusytown, nil, "pigweed-review.googlesource.com", nil)
	if p5.Name() != "busytown" {
		t.Errorf("expected busytown provider when explicitly configured, got %q", p5.Name())
	}

	// 6. Explicit buildbucket + busytown
	pcfgBoth := DefaultProjectConfig()
	pcfgBoth.CI.Providers = []string{"buildbucket", "busytown"}
	p6 := ResolveCIProvider(cfg, pcfgBoth, nil, "pigweed-review.googlesource.com", nil)
	if p6.Name() != "composite" {
		t.Errorf("expected composite provider when both configured, got %q", p6.Name())
	}
}

