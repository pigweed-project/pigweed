func TestBusytownProvider_RerunBuilds_DryRunAndLiveFallback(t *testing.T) {
	server := NewMockGerritServer(t)
	SetMockGit(t, nil)

	repoRoot := t.TempDir()
	if err := os.WriteFile(filepath.Join(repoRoot, ".ghish.toml"), []byte("[ci]\nproviders = [\"busytown\"]\n"), 0644); err != nil {
		t.Fatalf("failed to write .ghish.toml: %v", err)
	}
	oldMockCWD := MockCWD
	MockCWD = repoRoot
	t.Cleanup(func() {
		MockCWD = oldMockCWD
	})

	server.OnJSON("GET", "/changes/45678", http.StatusOK, gerrit.ChangeInfo{
		Number:          45678,
		Project:         "platform/system/core",
		Subject:         "Fix sensor HAL",
		Status:          "NEW",
		CurrentRevision: "rev2",
		Revisions: map[string]gerrit.RevisionInfo{
			"rev2": {Number: 2},
		},
	})

	server.OnJSON("GET", "/changes/45678/revisions/2/treetop~presubmittasks", http.StatusOK, map[string]any{
		"tasks": []map[string]any{
			{
				"name":     "firmware_host_tests",
				"target":   "firmware_host_tests",
				"status":   "FAIL",
				"build_id": "P99164207",
			},
		},
	})

	treetopRunActionCalled := 0
	treetopRunActionShould404 := false
	server.On("POST", "/changes/45678/revisions/2/treetop~runaction", func(w http.ResponseWriter, r *http.Request) {
		treetopRunActionCalled++
		if treetopRunActionShould404 {
			http.Error(w, "Not Found", http.StatusNotFound)
			return
		}
		server.RespondJSON(w, http.StatusOK, map[string]any{"status": "OK"})
	})

	reviewVotes := map[string]int{}
	server.On("POST", "/changes/45678/revisions/2/review", func(w http.ResponseWriter, r *http.Request) {
		var req gerrit.ReviewInput
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			t.Fatalf("failed to decode ReviewInput: %v", err)
		}
		for k, v := range req.Labels {
			reviewVotes[k] = v
		}
		server.RespondJSON(w, http.StatusOK, gerrit.ReviewResult{Labels: req.Labels})
	})

	// 1. Dry-run must NOT call treetop~runaction or review, and must print the dry-run line
	outDry, err := executeCommand(RootCmd, "run", "rerun", "45678", "--failed", "--dry-run")
	if err != nil {
		t.Fatalf("unexpected error from run rerun --dry-run: %v", err)
	}
	wantDry := "[dry-run] gerrit POST /changes/45678/revisions/2/treetop~runaction?service-id=presubmit&action-id=run (fallback: Presubmit-Ready+1)"
	if !strings.Contains(outDry, wantDry) {
		t.Errorf("expected dry-run output to contain %q, got:\n%s", wantDry, outDry)
	}
	if treetopRunActionCalled != 0 || len(reviewVotes) != 0 {
		t.Errorf("dry-run mutated server state: treetopRunActionCalled=%d, reviewVotes=%v", treetopRunActionCalled, reviewVotes)
	}

	// 2. Live rerun when treetop~runaction succeeds (200 OK)
	_, err = executeCommand(RootCmd, "run", "rerun", "45678", "--failed")
	if err != nil {
		t.Fatalf("unexpected error from live run rerun (treetop~runaction 200): %v", err)
	}
	if treetopRunActionCalled != 1 {
		t.Errorf("expected treetop~runaction to be called once, got %d", treetopRunActionCalled)
	}
	if len(reviewVotes) != 0 {
		t.Errorf("expected no fallback review vote when treetop~runaction succeeded, got %v", reviewVotes)
	}

	// 3. Live rerun when treetop~runaction returns 404 -> falls back to Presubmit-Ready+1
	treetopRunActionShould404 = true
	_, err = executeCommand(RootCmd, "run", "rerun", "45678", "--failed")
	if err != nil {
		t.Fatalf("unexpected error from live run rerun (404 fallback): %v", err)
	}
	if reviewVotes["Presubmit-Ready"] != 1 {
		t.Errorf("expected fallback vote Presubmit-Ready=+1, got %v", reviewVotes)
	}
}

