func TestCompositeCIProvider_OneProviderEmptyOrError(t *testing.T) {
	ctx := context.Background()

	// Case 1: Buildbucket returns 0 builds, Busytown returns 1 build -> returns 1 build
	server := NewMockGerritServer(t)
	SetMockGit(t, nil)
	server.OnSearchBuilds() // 0 Buildbucket builds
	change := &gerrit.ChangeInfo{
		Number: 99999,
		Messages: []gerrit.ChangeMessageInfo{
			{
				RevisionNumber: 1,
				Tag:            "autogenerated:TreeHugger:Verify-Pass",
				Message:        "Patch Set 1: Presubmit-Verified+2\nWorkplan ID: L11223344\n",
			},
		},
	}
	comp := &CompositeCIProvider{
		Providers: []CIProvider{
			&BuildbucketProvider{},
			&BusytownProvider{},
		},
	}
	builds, err := comp.SearchBuilds(ctx, "android-review.googlesource.com", 99999, 1, change)
	if err != nil {
		t.Fatalf("unexpected error when one provider returns 0 builds and the other succeeds: %v", err)
	}
	if len(builds) != 1 || builds[0].ID != "L11223344" {
		t.Errorf("expected 1 Busytown build L11223344, got %+v", builds)
	}

	// Case 2: One provider returns an error while another returns builds -> logs warning to ErrOut and returns builds
	var errBuf strings.Builder
	compWithErr := &CompositeCIProvider{
		Providers: []CIProvider{
			&failingStubCIProvider{name: "buildbucket", err: fmt.Errorf("rpc timeout")},
			&BusytownProvider{},
		},
		ErrOut: &errBuf,
	}
	builds2, err2 := compWithErr.SearchBuilds(ctx, "android-review.googlesource.com", 99999, 1, change)
	if err2 != nil {
		t.Fatalf("unexpected error when one provider fails and the other returns builds: %v", err2)
	}
	if len(builds2) != 1 || builds2[0].ID != "L11223344" {
		t.Errorf("expected 1 Busytown build L11223344, got %+v", builds2)
	}
	if !strings.Contains(errBuf.String(), "Warning: CI provider buildbucket failed: rpc timeout") {
		t.Errorf("expected warning logged to ErrOut, got %q", errBuf.String())
	}
}

func TestIsBusytownBuildID_And_ParseBusytownBuildTarget(t *testing.T) {
	tests := []struct {
		id       string
		target   string
		wantIsBT bool
		wantBID  string
		wantTgt  string
		wantOK   bool
	}{
		{id: "P99164207", wantIsBT: true, wantBID: "P99164207", wantTgt: "", wantOK: true},
		{id: "L87654321", wantIsBT: true, wantBID: "L87654321", wantTgt: "", wantOK: true},
		{id: "I1234567", wantIsBT: true, wantBID: "I1234567", wantTgt: "", wantOK: true},
		{id: "12345678", wantIsBT: true, wantBID: "12345678", wantTgt: "", wantOK: true},
		{id: "12345678", target: "device_arm64-userdebug", wantIsBT: true, wantBID: "12345678", wantTgt: "device_arm64-userdebug", wantOK: true},
		{id: "P99164207/sensor_unit_tests", wantIsBT: true, wantBID: "P99164207", wantTgt: "sensor_unit_tests", wantOK: true},
		{id: "12345678/device_arm64-userdebug", wantIsBT: true, wantBID: "12345678", wantTgt: "device_arm64-userdebug", wantOK: true},
		{id: "12345", wantIsBT: false, wantOK: false},
		{id: "8680709829694997521", wantIsBT: false, wantOK: false},
	}

	for _, tc := range tests {
		if got := IsBusytownBuildID(tc.id); got != tc.wantIsBT {
			t.Errorf("IsBusytownBuildID(%q) = %v, want %v", tc.id, got, tc.wantIsBT)
		}
		gotBID, gotTgt, gotOK := ParseBusytownBuildTarget(tc.id, tc.target)
		if gotOK != tc.wantOK || gotBID != tc.wantBID || gotTgt != tc.wantTgt {
			t.Errorf("ParseBusytownBuildTarget(%q, %q) = (%q, %q, %v), want (%q, %q, %v)",
				tc.id, tc.target, gotBID, gotTgt, gotOK, tc.wantBID, tc.wantTgt, tc.wantOK)
		}
	}
}
