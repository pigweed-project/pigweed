"""Tests Python enums generated by pw_py_enum_library."""

import enum
import unittest

from pw_enum_private.toml_enums import TomlEnum, TomlStatus


class JsonEnumPyTest(unittest.TestCase):
    """Tests Python enums generated from TOML and JSON."""

    def test_values(self) -> None:
        self.assertTrue(issubclass(TomlEnum, enum.IntEnum))
        self.assertEqual(TomlEnum.NEGATIVE, -2)
        self.assertEqual(TomlEnum.FIRST, 0)
        self.assertIs(TomlEnum.ALIAS_SECOND, TomlEnum.SECOND)
        self.assertEqual(TomlEnum.FROM_BASE, 11)  # JsonBaseEnum.TEN + 1
        self.assertEqual(TomlEnum.CUSTOM, 12)
        self.assertEqual(TomlStatus.BROKEN, 16)

    def test_display_names(self) -> None:
        self.assertEqual(str(TomlEnum.SECOND), "ALIAS_SECOND|SECOND")
        self.assertEqual(str(TomlEnum.CUSTOM), "custom_name")
        self.assertEqual(f"{TomlStatus.BUSY}", "BUSY")

    def test_token_domain(self) -> None:
        self.assertRegex(
            TomlEnum.__pw_enum_token_domain__,
            r"^::pw::enum_test::toml::_pw_enum_[0-9a-f]{12}::TomlEnum$",
        )

    def test_status(self) -> None:
        self.assertTrue(issubclass(TomlStatus, enum.IntEnum))
        self.assertTrue(TomlStatus.OK.ok())
        self.assertFalse(TomlStatus.BUSY.ok())
        self.assertFalse(TomlStatus(16).ok())

    def test_is_valid(self) -> None:
        self.assertTrue(TomlEnum.is_valid(11))
        self.assertFalse(TomlEnum.is_valid(3))


if __name__ == "__main__":
    unittest.main()
