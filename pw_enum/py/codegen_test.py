class TestCcHeader(unittest.TestCase):
    """Tests C++ header generation."""

    def test_header(self) -> None:
        header = "\n".join(generate_cc_header(_SOURCE, _ENUMS)) + "\n"
        self.assertEqual(header, _EXPECTED_HEADER)

    def test_large_values(self) -> None:
        values = (
            ("int64", -(2**63), "(-9223372036854775807ll - 1)"),
            ("int64", 2**40, "1099511627776ll"),
            ("int32", -(2**31), "-2147483648ll"),
            ("uint32", 2**32 - 1, "4294967295u"),
            ("uint64", 2**64 - 1, "18446744073709551615ull"),
        )
        for type_name, value, literal in values:
            with self.subTest(type_name=type_name, value=value):
                desc = EnumDescriptor(
                    name="Big",
                    scopes=("ns",),
                    cc_full_name="::ns::Big",
                    line=0,
                    values=(EnumValue("kBig", value, "BIG", "BIG"),),
                    namespace=("ns",),
                    underlying_type=type_name,
                )
                header = "\n".join(generate_cc_header("a.json", (desc,)))
                self.assertIn(f"  kBig = {literal},\n", header)

    def test_doc_cannot_end_with_backslash(self) -> None:
        for enum_doc, value_doc in (("C:\\", ""), ("", "a\\ \nb")):
            with self.subTest(enum_doc=enum_doc, value_doc=value_doc):
                desc = EnumDescriptor(
                    name="E",
                    scopes=("ns",),
                    cc_full_name="::ns::E",
                    line=0,
                    values=(EnumValue("kA", 0, "A", "A", value_doc),),
                    namespace=("ns",),
                    underlying_type="int32",
                    doc=enum_doc,
                )
                with self.assertRaisesRegex(ValueError, "backslash"):
                    list(generate_cc_header("a.json", (desc,)))


class TestPyModule(unittest.TestCase):
    """Tests Python module generation."""

    def setUp(self) -> None:
        self.source = "\n".join(generate_py_module(_SOURCE, _ENUMS)) + "\n"
        self.module: dict[str, Any] = {}
        exec(  # pylint: disable=exec-used
            compile(self.source, "my_enums.py", "exec"), self.module
        )

    def test_exports(self) -> None:
        self.assertEqual(self.module["__all__"], ["MyEnum", "MyStatus"])
        self.assertIn(
            '"""Enums generated by pw_enum from path/to/my_enums.json."""',
            self.source,
        )

    def test_members(self) -> None:
        my_enum = self.module["MyEnum"]
        self.assertTrue(issubclass(my_enum, enum.IntEnum))
        self.assertEqual(
            [(m.name, m.value) for m in my_enum],
            [("ALPHA", 0), ("BETA", 1), ("CUSTOM", 7), ("NEGATIVE", -5)],
        )
        self.assertIs(my_enum.ALIAS_BETA, my_enum.BETA)
        self.assertEqual(my_enum.CUSTOM, 7)
        self.assertEqual(
            inspect.getdoc(my_enum), "My enum.\n\nWith multiple lines."
        )
        self.assertIn(
            '    ALPHA = 0\n    """The first value."""\n', self.source
        )
        self.assertIn("    CUSTOM = 7\n    'Has \"quotes\"'\n", self.source)

    def test_display_names(self) -> None:
        my_enum = self.module["MyEnum"]
        self.assertEqual(str(my_enum.ALPHA), "ALPHA")
        self.assertEqual(str(my_enum.ALIAS_BETA), "ALIAS_BETA|BETA")
        self.assertEqual(str(my_enum.CUSTOM), 'it\'s "custom"')
        self.assertEqual(f"{my_enum.BETA}", "ALIAS_BETA|BETA")
        self.assertEqual(f"{my_enum.CUSTOM:03d}", "007")

    def test_token_domain(self) -> None:
        self.assertEqual(
            self.module["MyEnum"].__pw_enum_token_domain__,
            _ENUM.cc_versioned_name,
        )
        self.assertEqual(
            self.module["MyStatus"].__pw_enum_token_domain__,
            _STATUS_ENUM.cc_versioned_name,
        )

    def test_status(self) -> None:
        # Status enums are named after their status, not their code.
        self.assertNotIn("Code", self.module)
        my_status = self.module["MyStatus"]
        self.assertTrue(issubclass(my_status, enum.IntEnum))
        self.assertEqual(
            [(m.name, m.value) for m in my_status], [("OK", 0), ("BUSY", 1)]
        )
        self.assertTrue(my_status.OK.ok())
        self.assertFalse(my_status.BUSY.ok())
        self.assertEqual(str(my_status.BUSY), "BUSY")

    def test_only_status_enums_have_ok(self) -> None:
        self.assertFalse(hasattr(self.module["MyEnum"], "ok"))

    def test_is_valid(self) -> None:
        my_enum = self.module["MyEnum"]
        self.assertTrue(my_enum.is_valid(-5))
        self.assertTrue(my_enum.is_valid(my_enum.BETA))
        self.assertFalse(my_enum.is_valid(2))
        self.assertFalse(my_enum.is_valid(True))

    def test_requires_canonical_names(self) -> None:
        header_enum = EnumDescriptor(
            name="E",
            scopes=("ns",),
            cc_full_name="::ns::E",
            line=1,
            values=(EnumValue("kA", 0, "A"),),
        )
        with self.assertRaisesRegex(ValueError, "no canonical name"):
            list(generate_py_module("a.h", (header_enum,)))


class TestCodegenCli(unittest.TestCase):
    """Tests the pw_enum.codegen command-line interface."""

    def setUp(self) -> None:
        self._temp_dir = tempfile.TemporaryDirectory()
        self._dir = Path(self._temp_dir.name)
        self._src = self._dir / "my_enums.json"
        self._src.write_text(
            json.dumps(
                {
                    "namespace": "my.pkg",
                    "enums": {
                        "MyEnum": {
                            "values": [{"name": "ALPHA"}, {"name": "BETA"}],
                        }
                    },
                }
            ),
            encoding="utf-8",
        )

    def tearDown(self) -> None:
        self._temp_dir.cleanup()

    def test_check_and_depfile(self) -> None:
        depfile = self._dir / "check.d"
        stamp = self._dir / "check.stamp"
        self.assertEqual(
            codegen.main(
                [
                    "check",
                    "--sources",
                    str(self._src),
                    "--depfile",
                    str(depfile),
                    "--stamp",
                    str(stamp),
                ]
            ),
            0,
        )
        self.assertIn(self._src.as_posix(), depfile.read_text(encoding="utf-8"))
        self.assertTrue(stamp.is_file())

    def test_cc_and_py_generation_with_argfile(self) -> None:
        cc_out = self._dir / "my_enums.enum.h"
        py_out = self._dir / "my_enums.py"
        empty_deps = self._dir / "empty_deps.txt"
        empty_deps.write_text("\n", encoding="utf-8")
        argfile = self._dir / "args.txt"
        argfile.write_text(
            f"cc\n--sources\n{self._src}\n--deps\n@{empty_deps}\n"
            f"--transitive-deps\n{self._src}\n--outputs\n{cc_out}\n",
            encoding="utf-8",
        )
        self.assertEqual(codegen.main([f"@{argfile}"]), 0)
        self.assertIn("enum class MyEnum", cc_out.read_text(encoding="utf-8"))

        self.assertEqual(
            codegen.main(
                ["py", "--sources", str(self._src), "--outputs", str(py_out)]
            ),
            0,
        )
        self.assertIn(
            "class MyEnum(enum.IntEnum):", py_out.read_text(encoding="utf-8")
        )

    def test_toml_source(self) -> None:
        toml_src = self._dir / "my_enums.toml"
        toml_src.write_text(
            'namespace = "my.pkg"\n'
            "[enums.MyEnum]\n"
            'values = [{ name = "ALPHA" }, { name = "BETA" }]\n',
            encoding="utf-8",
        )
        cc_out = self._dir / "my_enums.enum.h"
        py_out = self._dir / "my_enums.py"
        self.assertEqual(
            codegen.main(
                ["cc", "--sources", str(toml_src), "--outputs", str(cc_out)]
            ),
            0,
        )
        self.assertIn("enum class MyEnum", cc_out.read_text(encoding="utf-8"))

        self.assertEqual(
            codegen.main(
                ["py", "--sources", str(toml_src), "--outputs", str(py_out)]
            ),
            0,
        )
        self.assertIn(
            "class MyEnum(enum.IntEnum):", py_out.read_text(encoding="utf-8")
        )

    def test_invalid_py_module_name(self) -> None:
        bad_out = self._dir / "bad-name.py"
        self.assertEqual(
            codegen.main(
                ["py", "--sources", str(self._src), "--outputs", str(bad_out)]
            ),
            1,
        )

    def test_invalid_py_import_path(self) -> None:
        py_out = self._dir / "my_enums.py"
        for import_path in ("bad-pkg/my_enums", "pkg/class/my_enums"):
            with self.subTest(import_path=import_path):
                self.assertEqual(
                    codegen.main(
                        [
                            "py",
                            "--sources",
                            str(self._src),
                            "--outputs",
                            str(py_out),
                            "--import-paths",
                            import_path,
                        ]
                    ),
                    1,
                )
                self.assertFalse(py_out.exists())

    def test_valid_py_import_path(self) -> None:
        py_out = self._dir / "my_enums.py"
        self.assertEqual(
            codegen.main(
                [
                    "py",
                    "--sources",
                    str(self._src),
                    "--outputs",
                    str(py_out),
                    "--import-paths",
                    "my/pkg/my_enums",
                ]
            ),
            0,
        )
        self.assertTrue(py_out.is_file())

    def test_missing_source(self) -> None:
        missing = self._dir / "missing.json"
        self.assertEqual(
            codegen.main(
                [
                    "check",
                    "--sources",
                    str(missing),
                    "--stamp",
                    str(self._dir / "check.stamp"),
                ]
            ),
            1,
        )

    def test_depfile_escaping(self) -> None:
        special = self._dir / "dir with $pecial #chars" / "my_enums.json"
        special.parent.mkdir()
        special.write_text(
            self._src.read_text(encoding="utf-8"), encoding="utf-8"
        )
        depfile = self._dir / "check.d"
        self.assertEqual(
            codegen.main(
                [
                    "check",
                    "--sources",
                    str(special),
                    "--depfile",
                    str(depfile),
                    "--stamp",
                    str(self._dir / "check.stamp"),
                ]
            ),
            0,
        )
        self.assertIn(
            "dir\\ with\\ $$pecial\\ \\#chars/my_enums.json",
            depfile.read_text(encoding="utf-8"),
        )


