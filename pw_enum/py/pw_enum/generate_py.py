"""Generates Python modules for enums defined in pw_enum data files.

Generated modules only depend on the Python standard library. Each enum is a
statically defined ``enum.IntEnum``, so type checkers fully understand it.

Python does not distinguish between a status and its code, so an enum with a
status generates a single class, named after the status, with an ``ok()``
method.
"""

from __future__ import annotations

from collections.abc import Iterator, Sequence

from pw_enum.parse import EnumDescriptor, EnumValue
from pw_codegen import python


def _py_name(value: EnumValue) -> str:
    if not value.canonical_name:
        raise ValueError(
            f"Enumerator {value.cc_name} has no canonical name; Python code "
            "can only be generated for enums defined in pw_enum data files"
        )
    return value.canonical_name


def _class_name(enum_desc: EnumDescriptor) -> str:
    """Returns the enum class name; status name is used statuses."""
    return enum_desc.status.name if enum_desc.status else enum_desc.name


def _ok_name(enum_desc: EnumDescriptor) -> str:
    assert enum_desc.status is not None
    ok_code = enum_desc.status.ok_code
    return _py_name(next(v for v in enum_desc.values if v.cc_name == ok_code))


def _generate_enum(enum_desc: EnumDescriptor) -> Iterator[str]:
    class_name = _class_name(enum_desc)
    names_var = f"_{class_name}_DISPLAY_NAMES"
    first_name: dict[int, str] = {}

    yield ""
    yield ""
    yield f"class {class_name}(enum.IntEnum):"
    yield from python.docstring(
        enum_desc.doc
        or f"The {'.'.join(enum_desc.namespace + (class_name,))} enum.",
        "    ",
    )
    yield ""

    for value in enum_desc.values:
        name = _py_name(value)
        alias = first_name.setdefault(value.value, name)
        comment = f"  # Alias of {alias}." if alias != name else ""
        yield f"    {name} = {value.value}{comment}"
        yield from python.docstring(value.doc, "    ")

    yield ""
    yield "    __pw_enum_token_domain__ = " + python.string_literal(
        enum_desc.cc_versioned_name
    )
    yield ""
    yield "    def __str__(self) -> str:"
    yield '        """Returns the display name, like pw::EnumToString."""'
    yield f"        return {names_var}[self.value]"
    yield ""
    yield "    def __format__(self, format_spec: str) -> str:"
    yield '        """Formats as the display name or as an int with a spec."""'
    yield "        if format_spec:"
    yield "            return int.__format__(self, format_spec)"
    yield "        return str(self)"
    yield ""
    if enum_desc.status is not None:
        ok_name = _ok_name(enum_desc)
        yield "    def ok(self) -> bool:"
        yield f'        """Returns whether this is {ok_name}."""'
        yield f"        return self is {class_name}.{ok_name}"
        yield ""
    yield "    @classmethod"
    yield "    def is_valid(cls, value: int) -> bool:"
    yield '        """Returns whether the integer is a value of this enum."""'
    yield (
        f"        return not isinstance(value, bool) and value in {names_var}"
    )
    yield ""
    yield ""
    yield f"{names_var}: dict[int, str] = {{"
    for value, display_name in enum_desc.unique_values():
        yield f"    {value.value}: {python.string_literal(display_name)},"
    yield "}"


def generate_py_module(
    source: str, enums: Sequence[EnumDescriptor]
) -> Iterator[str]:
    """Generates a Python module for enums from a pw_enum source."""
    yield f"# Generated by pw_enum from {source}. DO NOT EDIT."
    yield f'"""Enums generated by pw_enum from {source}."""'
    yield ""
    yield "import enum"
    yield ""
    yield "__all__ = ["
    for enum_desc in enums:
        yield f"    {python.string_literal(_class_name(enum_desc))},"
    yield "]"

    for enum_desc in enums:
        yield from _generate_enum(enum_desc)
