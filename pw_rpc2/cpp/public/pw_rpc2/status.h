#pragma once

#include <cstdint>

#include "pw_enum/generate.h"
#include "pw_result/result.h"

namespace pw::rpc2 {

/// @submodule{pw_rpc2,status}

/// The outcome of a `pw_rpc2` operation, expressed as what the caller should
/// do next. Use `RpcStatus` objects instead of `RpcCode`.
///
/// Each code maps to one distinct action, so the code alone is enough to
/// decide how to respond. The precise cause of an error is not part of the
/// status: `pw_rpc2` logs it where it is detected.
///
/// `RpcCode` values are never sent on the wire. Endpoints exchange more
/// precise error codes, which the receiver converts to an `RpcCode`. The
/// numeric values may change.
enum class RpcCode : uint8_t {
  /// The operation succeeded.
  ///
  /// **Action:** Continue.
  kOk = 0,

  /// The peer finished its stream and every message it sent has been read.
  /// Not a failure. For a client, the RPC finished successfully.
  ///
  /// **Action:** Stop reading.
  kEndOfStream,

  /// Application code on either side ended the call, explicitly (with
  /// `Cancel()`) or implicitly (for example, by dropping a call handle).
  ///
  /// **Action:** Stop work on the call. Don't retry automatically: application
  /// logic chose to end it.
  kCancelled,

  /// You closed the `Client` or `Server`, or the object you used is empty.
  ///
  /// **Action:** Up to you; you closed this call.
  kClosed,

  /// This call's outbound direction is closed. The call itself may still be
  /// open.
  ///
  /// **Action:** Stop writing. If a response or more messages are expected,
  /// keep reading.
  kWriteClosed,

  /// The connection is gone or could not be made, for a reason that a new
  /// connection can fix. Whether the peer processed in-flight calls is
  /// unknown.
  ///
  /// **Action:** Create a new `Client`, with backoff. Retry in-flight calls
  /// only if they are idempotent. On a server, stop work on the call.
  kDisconnected,

  /// This endpoint could not allocate memory for the operation. The peer was
  /// not involved.
  ///
  /// **Action:** Free local resources (finish or drop other calls, or run
  /// fewer at once), then retry. Backing off against the server won't help.
  kResourceExhausted,

  /// The server could not take the call right now. The method never ran.
  ///
  /// **Action:** Retry later with backoff. Retrying is safe even for methods
  /// that are not idempotent.
  kUnavailable,

  /// The server started the call, then ended it for a reason outside the
  /// method's control. The method may have partly run.
  ///
  /// **Action:** Retry only if the method is idempotent; otherwise, report the
  /// failure.
  kAborted,

  /// The server does not offer this method in the form the client expects.
  ///
  /// **Action:** Don't retry against this server. Fall back (for example, to an
  /// older API or a feature-detected path), or fix the deployment or schema
  /// mismatch.
  kUnimplemented,

  /// An outbound message is larger than the transport or reservation allows.
  /// Nothing was sent, and the call is still open.
  ///
  /// **Action:** Send a smaller message (for example, split it), or raise the
  /// reservation or transport limit.
  kMessageTooLarge,

  /// A message could not be encoded or decoded.
  ///
  /// **Action:** Don't resend the same message unchanged; fix it or the schema
  /// mismatch. What remains of the call depends on where the error occurred:
  ///
  /// - Local write: nothing was sent, and the call is still open.
  /// - Local read: that one message is dropped. A stream stays open, and the
  ///   next read may succeed.
  /// - The server could not decode the request: the call is over.
  kDataError,

  /// An endpoint broke the protocol, the endpoints' protocol versions are
  /// incompatible, or an RPC implementation has a bug. If the error closed the
  /// connection, later calls on the same `Client` also report
  /// `kProtocolError`.
  ///
  /// **Action:** Nothing fixes this at runtime: reconnecting and retrying won't
  /// help. Log or report it; it needs a code or deployment fix.
  kProtocolError,
};

/// @class RpcStatus
/// @ingroup pw_rpc2_status
/// The status returned by `pw_rpc2` APIs. Wraps an `RpcCode`.
class RpcStatus;  // The class is generated by `PW_ENUM_STATUS`

/// A value of type `T`, or the `RpcStatus` explaining why there is none.
template <typename T>
using RpcResult = ::pw::Result<T, RpcStatus>;

/// @endsubmodule

}  // namespace pw::rpc2

PW_ENUM_STATUS(pw::rpc2::RpcStatus,
               RpcCode::kOk,
               kOk,
               kEndOfStream,
               kCancelled,
               kClosed,
               kWriteClosed,
               kDisconnected,
               kResourceExhausted,
               kUnavailable,
               kAborted,
               kUnimplemented,
               kMessageTooLarge,
               kDataError,
               kProtocolError);
