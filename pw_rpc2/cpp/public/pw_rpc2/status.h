#pragma once

#include "pw_result/result.h"
#include "pw_rpc2/rpc_code.h"  // IWYU pragma: export

namespace pw::rpc2 {

/// @submodule{pw_rpc2,status}

/// @enum RpcCode
/// @ingroup pw_rpc2_status

/// @class RpcStatus
/// @ingroup pw_rpc2_status
/// The status returned by `pw_rpc2` APIs. Wraps an `RpcCode`. Use `RpcStatus`
/// objects instead of raw `RpcCode` values.
class RpcStatus;  // The class is generated by `pw_enum`

/// A value of type `T`, or the `RpcStatus` explaining why there is none.
template <typename T>
using RpcResult = ::pw::Result<T, RpcStatus>;

/// @endsubmodule

}  // namespace pw::rpc2
